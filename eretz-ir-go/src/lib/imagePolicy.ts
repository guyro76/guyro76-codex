/**
 * אילו קטגוריות מותר לשלוף להן תמונה.
 *
 * ## למה זו רשימת היתר ולא רשימת איסור
 *
 * הצינור שלף תמונה לכל קטגוריה, כולל **"אישיות מפורסמת"** — כלומר
 * צילומים של בני אדם אמיתיים, מזוהים, בתוך אפליקציה מסחרית.
 *
 * רישיון Creative Commons מסדיר את **זכות היוצרים של הצלם** ותו לא.
 * הוא אינו נותן רשות להשתמש בדמותו של המצולם. בישראל שימוש בדמותו
 * של אדם לשם רווח נופל לחוק הגנת הפרטיות (סעיף 2(6)) ולזכות הפרסום,
 * ואישיות ציבורית דווקא מקפידה על זה יותר ולא פחות.
 *
 * לכן: **רשימת היתר**. קטגוריה חדשה שתתווסף למשחק לא תקבל תמונות עד
 * שמישהו יחשוב עליה במפורש — וזה בדיוק הכיוון הבטוח לטעות בו.
 */

/**
 * קטגוריות שהתשובה בהן היא מקום, חפץ, צמח או בעל חיים — לא אדם.
 *
 * `israelplace` נמצא כאן ו-`celebrity` לא, וזה כל ההבדל.
 */
export const PHOTO_FREE_CATEGORIES: string[] = [
  'country',
  'city',
  'israelplace',
  'animal',
  'seaanimal',
  'bird',
  'insect',
  'plant',
  'flower',
  'fruit',
  'vegetable',
  'tree',
  'food',
  'dessert',
  'drink',
  'inanimate'
];

/** האם מותר להביא תמונה לקטגוריה הזו */
export function photosAllowed(categoryId: string): boolean {
  return PHOTO_FREE_CATEGORIES.includes(categoryId);
}
