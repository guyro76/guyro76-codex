/**
 * סינון שם תצוגה שעובר בין מכשירים.
 *
 * ## למה זה קיים
 *
 * המשחק אינו מאפשר מלל חופשי בין ילדים, ומה שנוסע בקישור האתגר הוא
 * מספרים בלבד — חוץ משדה אחד: **שם התצוגה של המאתגר**. בלי הסינון
 * הזה השדה הוא ערוץ הודעות לכל דבר, כי ילד יכול לשנות את שמו ל-
 * "בוא נריב", לקללה, או למספר טלפון, ולשלוח אתגרים.
 *
 * ## שלוש ההגנות, לפי סדר החשיבות
 *
 * 1. **מילה אחת בלבד.** הודעה מחייבת הפרדה בין מילים. לוקחים את
 *    האסימון הראשון ומוותרים על השאר, ולכן "בוא נריב" הופך ל"בוא".
 *    זו ההגנה החזקה מבין השלוש: היא לא מסתמכת על רשימה.
 * 2. **מעט ספרות.** שם עם שלוש ספרות ומעלה נפסל, כי זה מספר טלפון
 *    או חלק ממנו — ניסיון ליצור קשר מחוץ למשחק. "דני2" עובר.
 * 3. **רשימת חסימה.** קללות ועלבונות נפוצים בעברית ובאנגלית.
 *    אחרונה בכוונה: רשימה אף פעם אינה שלמה, והיא משלימה את שתי
 *    הראשונות ולא מחליפה אותן.
 *
 * הסינון מופעל **בפענוח**, לא רק בשליחה. מי ששולח את הקישור יכול
 * לערוך אותו ביד, ולכן הגנה בצד השולח היא בקשה יפה בלבד.
 */

/** מה שמוצג במקום שם שנפסל */
export const FALLBACK_NAME = 'שחקן';

/** מקסימום ספרות בשם לגיטימי. שלוש כבר מריחות כמו מספר טלפון. */
export const MAX_DIGITS = 2;

/**
 * רשימת חסימה — קללות ועלבונות שילדים משתמשים בהם בפועל.
 *
 * מילים באורך 4 ומעלה נחסמות גם כחלק ממילה, כי הן כמעט תמיד
 * מכוונות. מילים קצרות יותר נחסמות רק בהתאמה מדויקת, אחרת "מזין"
 * ו"זינוק" היו נפסלים בגלל "זין".
 */
const BLOCKED = [
  // עברית
  'זין', 'כוס', 'חרא', 'זונה', 'שרמוטה', 'מניאק', 'מטומטם', 'מטומטמת',
  'אידיוט', 'טמבל', 'דביל', 'מפגר', 'מפגרת', 'בןזונה', 'לךתמות', 'תמות',
  'מכוער', 'מכוערת', 'שמן', 'שמנה', 'נאצי', 'היטלר', 'למות', 'שתמות',
  // אנגלית
  'fuck', 'shit', 'bitch', 'cunt', 'dick', 'whore', 'slut', 'bastard',
  'retard', 'idiot', 'stupid', 'moron', 'loser', 'ugly', 'nazi', 'hitler',
  'kill', 'die', 'sex', 'porn'
];

/** אותיות סופיות → רגילות, כדי ש"כוסס" ו"זינן" לא יתחמקו */
const FINALS: Record<string, string> = { 'ם': 'מ', 'ן': 'נ', 'ץ': 'צ', 'ף': 'פ', 'ך': 'כ' };

/** החלפות leetspeak נפוצות באנגלית */
const LEET: Record<string, string> = { '0': 'o', '1': 'i', '3': 'e', '4': 'a', '5': 's', '7': 't', '@': 'a', '$': 's' };

/**
 * צורה מנורמלת להשוואה מול הרשימה.
 *
 * מסירה כל מה שאינו אות, מיישרת אותיות סופיות ומפענחת leetspeak —
 * כדי ש-"f.u.c.k", "FUCK", "fu3k" ו-"כוסס" ייתפסו כמו המקור.
 */
export function normalizeForFilter(text: string): string {
  return (text ?? '')
    .toLowerCase()
    .split('')
    .map((ch) => LEET[ch] ?? FINALS[ch] ?? ch)
    .join('')
    .replace(/[^a-zא-ת]/g, '');
}

/** האם הטקסט נושא מילה חסומה */
export function hasBlockedWord(text: string): boolean {
  const norm = normalizeForFilter(text);
  if (!norm) return false;
  return BLOCKED.some((word) => {
    const w = normalizeForFilter(word);
    // מילה ארוכה מכוונת גם כשהיא חלק ממילה; קצרה — רק בהתאמה מדויקת,
    // אחרת שמות ומילים תמימות נפסלים
    return w.length >= 4 ? norm.includes(w) : norm === w;
  });
}

/**
 * שם תצוגה בטוח להעברה בין מכשירים.
 *
 * תמיד מחזיר משהו שאפשר להציג — שם שנפסל הופך ל`שחקן` ולא לריק,
 * כי מסך שמראה "‏ מאתגר אותך" נראה שבור.
 */
export function safeDisplayName(raw: string, maxLength: number): string {
  // מילה אחת בלבד — ההגנה שאינה תלויה בשום רשימה
  const firstWord = (raw ?? '').trim().split(/\s+/)[0] ?? '';

  const cleaned = firstWord
    .replace(/[^֐-׿a-zA-Z0-9'״׳]/g, '')
    .slice(0, maxLength)
    .trim();

  if (!cleaned) return FALLBACK_NAME;
  if ((cleaned.match(/\d/g)?.length ?? 0) > MAX_DIGITS) return FALLBACK_NAME;

  /**
   * נבדקות **שתי** הצורות, וזה לא ייתור.
   *
   * הניקוי מסיר תווים שאינם אותיות, ולכן "$hit" הופך ל-"hit" —
   * ואז ה-leet כבר לא רואה את ה-$ ולא ממיר אותו ל-s. בדיקה על
   * הצורה הגולמית תופסת בדיוק את זה, ובדיקה על הנקייה תופסת
   * מקרים שבהם דווקא הקיצוץ באורך חשף מילה חסומה.
   */
  if (hasBlockedWord(firstWord) || hasBlockedWord(cleaned)) return FALLBACK_NAME;
  return cleaned;
}
