/**
 * משפטים מוכנים בין שחקנים שמכירים זה את זה.
 *
 * זה לא צ'אט, וההבדל אינו סמנטי אלא נמדד: **בקישור נוסע מספר, לא
 * טקסט**. כל מה שאפשר "לומר" הוא לבחור אחד מתוך הרשימה הסגורה
 * שלמטה, כלומר קיבולת הערוץ היא שלושה ביט. אי אפשר להלחין ממנה
 * הודעה, אי אפשר להבריח בה כתובת או מפגש, ולכן אין מה לסנן ואין
 * מה לדווח עליו — הכלל "ללא צ'אט פתוח בין ילדים" נשמר במלואו.
 *
 * ## הרשימה היא append-only
 *
 * המזהים נוסעים בקישורים שכבר נשלחו. שינוי הטקסט של מזהה קיים,
 * או שינוי הסדר, **משנה למפרע מה שילד אמר** — מישהו שכתב "בהצלחה"
 * יגלה שהוא אמר משהו אחר. מותר להוסיף מזהה חדש בסוף; אסור לגעת
 * בקיימים. יש בדיקה שנועלת את זה.
 *
 * ## למה דווקא המשפטים האלה
 *
 * כולם חיוביים או ניטרליים, ואף אחד מהם אינו ניתן לשימוש כעלבון —
 * גם לא בהקשר של הפסד. רשימה שמכילה "הפסדת!" או "חלש" הופכת כל
 * משחק לכלי לעג, וזה נזק אמיתי גם בלי טקסט חופשי.
 */
export interface QuickPhrase {
  /** מזהה יציב. נוסע בקישור. לעולם לא ממוחזר ולא משנה משמעות. */
  id: number;
  text: string;
  icon: string;
}

export const QUICK_PHRASES: QuickPhrase[] = [
  { id: 1, icon: '🍀', text: 'בהצלחה!' },
  { id: 2, icon: '👏', text: 'כל הכבוד!' },
  { id: 3, icon: '😮', text: 'וואו, קשה!' },
  { id: 4, icon: '🔥', text: 'תנסה לעבור את זה' },
  { id: 5, icon: '🙂', text: 'היה כיף' },
  { id: 6, icon: '🔁', text: 'עוד סיבוב?' },
  { id: 7, icon: '💪', text: 'הפעם אני מנצח' },
  { id: 8, icon: '🤝', text: 'משחק יפה' }
];

/** המשפט לפי מזהה, או `null` למזהה שאינו קיים בגרסה הזו */
export function phraseById(id: number | undefined | null): QuickPhrase | null {
  if (typeof id !== 'number' || !Number.isInteger(id)) return null;
  return QUICK_PHRASES.find((p) => p.id === id) ?? null;
}

/**
 * האם המזהה תקף.
 *
 * משמש בפענוח: מזהה שאינו ברשימה **נזרק בשקט** ולא מוצג. כך קישור
 * שנערך ביד לא יכול להוסיף משפט חדש, וקישור מגרסה חדשה יותר לא
 * ישבור מסך אצל מי שעוד לא עדכן.
 */
export function isKnownPhrase(id: unknown): id is number {
  return typeof id === 'number' && phraseById(id) !== null;
}

/** תצוגה מלאה של משפט, לשורת הצ'אט ולטקסט השיתוף */
export function phraseLabel(id: number | undefined | null): string | null {
  const p = phraseById(id);
  return p ? `${p.icon} ${p.text}` : null;
}
