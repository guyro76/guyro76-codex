/**
 * בוחרת שורה מהקבוצה, ומעדיפה שורה שעוד לא נאמרה. בלי זה ארצי חוזר
 * על עצמו כבר בלחיצה השלישית, וזה בדיוק מה שגורם להפסיק ללחוץ עליו.
 */
export function pickLine(bucket: ArtziBucket, used: Set<string>, rand: () => number = Math.random): string {
  const pool = ARTZI_LINES[bucket];
  const fresh = pool.filter((l) => !used.has(l));
  const from = fresh.length > 0 ? fresh : pool;
  return from[Math.floor(rand() * from.length)];
}
