/** הטלה גלילית שווה-מרחקים ל-viewBox של 720×360 */
export const MAP_W = 720;
export const MAP_H = 360;

export function project(lat: number, lon: number): { x: number; y: number } {
  return {
    x: ((lon + 180) / 360) * MAP_W,
    y: ((90 - lat) / 180) * MAP_H
  };
}
