/**
 * המפתח הוא השם המנורמל, כי זה מה ששמור בתשובות של הילד — אותה
 * נורמליזציה שמשמשת את בדיקת התשובות, כך שאיות עם או בלי ניקוד
 * וגרשיים עדיין ימצא את המקום.
 */
export const PLACES: Map<string, Place & { name: string }> = new Map();

for (const [name, [lat, lon]] of Object.entries(COUNTRIES)) {
  PLACES.set(normalizeHebrew(name), { lat, lon, kind: 'country', name });
}
for (const [name, [lat, lon]] of Object.entries(CITIES)) {
  const key = normalizeHebrew(name);
  // מדינה ועיר באותו שם: המדינה קודמת, כי היא מה שילד מתכוון אליו
  if (!PLACES.has(key)) PLACES.set(key, { lat, lon, kind: 'city', name });
}

