/**
 * פאזלים של מקומות בארץ.
 *
 * הרעיון: בסוף כל סיבוב נופל חלק אחד של פאזל, ולא תמיד של אותו
 * פאזל — כך נאספים במקביל כמה לוחות, וכל אחד מהם נחשף לאט. התמונה
 * המלאה מתגלה רק כשכל החלקים נאספו.
 *
 * מאיפה התמונות: **אותו צינור מאומת של תמונות התשובות** — הערך
 * בוויקיפדיה העברית, עם הקרדיט והרישיון שמוצגים לצד התמונה. אין
 * כאן תמונות מיוצרות ואין תמונות ממקור לא ידוע. אחרי צפייה ראשונה
 * התמונה נשמרת במטמון והפאזל עובד גם בלי רשת.
 *
 * `lookup` חייב להיות **כותרת הערך המדויקת** בוויקיפדיה העברית:
 * שער האימות דורש התאמה מלאה בין הכותרת לשם המבוקש, ולכן שם מקורב
 * פשוט לא יחזיר תמונה — הפאזל יוצג עם מסגרות ריקות במקום עם תמונה
 * שגויה. זו ההתנהגות הרצויה.
 */
export interface Puzzle {
  id: string;
  /** שם התצוגה — וגם מה שמחפשים בוויקיפדיה */
  name: string;
  icon: string;
  region: string;
  /** מה מספרים לילד כשהפאזל הושלם */
  fact: string;
  cols: number;
  rows: number;
}

